-- ============================================================
-- دوال الصلاحيات (SECURITY DEFINER لمنع الحلقات)
-- ============================================================
create or replace function public.is_owner()
returns boolean
language sql stable security definer set search_path = public
as $$
  select exists(
    select 1 from public.profiles
    where auth_user_id = auth.uid()
      and role = 'owner'
      and status = 'allowed'
  );
$$;

create or replace function public.is_allowed_reader()
returns boolean
language sql stable security definer set search_path = public
as $$
  select exists(
    select 1 from public.profiles
    where auth_user_id = auth.uid()
      and status = 'allowed'
  );
$$;

-- ============================================================
-- سياسات profiles
-- ============================================================
drop policy if exists profiles_owner_all on public.profiles;
create policy profiles_owner_all on public.profiles
  for all to authenticated
  using (public.is_owner())
  with check (public.is_owner());

drop policy if exists profiles_self_read on public.profiles;
create policy profiles_self_read on public.profiles
  for select to authenticated
  using (auth_user_id = auth.uid());

-- ============================================================
-- سياسات dashboard_state
-- ============================================================
drop policy if exists dashboard_state_select on public.dashboard_state;
drop policy if exists dashboard_state_insert on public.dashboard_state;
drop policy if exists dashboard_state_update on public.dashboard_state;
drop policy if exists dashboard_state_anon_select on public.dashboard_state;
drop policy if exists dashboard_state_anon_insert on public.dashboard_state;
drop policy if exists dashboard_state_anon_update on public.dashboard_state;

create policy dashboard_state_select on public.dashboard_state
  for select to authenticated
  using (public.is_allowed_reader());

create policy dashboard_state_insert on public.dashboard_state
  for insert to authenticated
  with check (id = 1 and public.is_owner());

create policy dashboard_state_update on public.dashboard_state
  for update to authenticated
  using (id = 1 and public.is_owner())
  with check (id = 1 and public.is_owner());

