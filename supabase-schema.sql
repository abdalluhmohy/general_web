create extension if not exists pgcrypto;

-- ============================================================
-- الجدول 1: profiles — مستخدمو النظام (للمصادقة والصلاحيات)
-- ============================================================
create table if not exists public.profiles (
  id bigint generated by default as identity primary key,
  auth_user_id uuid unique references auth.users(id) on delete cascade,
  email text not null default '',
  full_name text not null default '',
  phone text not null default '',
  role text not null default 'reader' check (role in ('owner','reader')),
  status text not null default 'pending' check (status in ('pending','allowed','blocked')),
  avatar_url text not null default '',
  notes text not null default '',
  login_count integer not null default 0,
  last_login timestamptz,
  created_at timestamptz not null default now()
);

-- تأكيد وجود الأعمدة لو الجدول أُنشئ سابقًا بصيغة قديمة
alter table public.profiles add column if not exists email text not null default '';
alter table public.profiles add column if not exists avatar_url text not null default '';
alter table public.profiles add column if not exists notes text not null default '';

-- ============================================================
-- الجدول 2: dashboard_state — كل بيانات الموقع (JSON واحد)
-- ============================================================
create table if not exists public.dashboard_state (
  id integer primary key check (id = 1),
  data_json jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now(),
  updated_by uuid references auth.users(id) on delete set null
);

-- ============================================================
-- الجدول 3: employees — مزامنة الموظفين (للتقارير الخارجية)
-- ============================================================
create table if not exists public.employees (
  id bigint generated by default as identity primary key,
  emp_code text not null default '',
  name text not null,
  department text not null default '',
  is_manager boolean not null default false,
  role text not null default '',
  nationality text not null default '',
  phone text not null default '',
  email text not null default '',
  status text not null default 'active',
  salary numeric not null default 0,
  allowances numeric not null default 0,
  currency text not null default 'SDG',
  hire_date date,
  end_date date,
  end_reason text not null default '',
  passport_number text not null default '',
  passport_path text not null default '',
  photo_path text not null default '',
  notes text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists employees_status_idx on public.employees(status);
create index if not exists employees_department_idx on public.employees(department);

