create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id bigint generated by default as identity primary key,
  auth_user_id uuid unique constraint profiles_auth_user_fk references auth.users(id) on delete cascade,
  full_name text not null default '',
  phone text not null default '',
  role text not null default 'reader' check (role in ('owner', 'reader')),
  status text not null default 'allowed' check (status in ('allowed', 'blocked')),
  login_count integer not null default 0,
  last_login timestamptz,
  created_at timestamptz not null default now()
);

