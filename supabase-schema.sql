  for all to authenticated
  using (public.is_owner())
  with check (public.is_owner());

-- ============================================================
-- المُشغّل: إنشاء profile تلقائيًا عند إضافة مستخدم جديد
-- ============================================================
create or replace function public.handle_new_goldnile_user()
returns trigger
language plpgsql security definer
set search_path = public
as $$
begin
  insert into public.profiles(auth_user_id, email, full_name, role, status)
  values (
    new.id,
    coalesce(new.email, ''),
    coalesce(new.raw_user_meta_data->>'full_name', ''),
    'reader',
    'pending'
  )
  on conflict (auth_user_id) do update set
    email = excluded.email,
    full_name = excluded.full_name;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created_goldnile on auth.users;
create trigger on_auth_user_created_goldnile
after insert on auth.users
for each row execute function public.handle_new_goldnile_user();

