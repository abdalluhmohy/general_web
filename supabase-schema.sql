-- Compatibility migration: older versions may already have profiles.id as bigint.
-- The auth identity is deliberately stored in auth_user_id, which is uuid.
alter table public.profiles add column if not exists auth_user_id uuid;
do $$
begin
  if not exists (
    select 1 from pg_constraint
    where conname = 'profiles_auth_user_fk'
      and conrelid = 'public.profiles'::regclass
  ) then
    alter table public.profiles
      add constraint profiles_auth_user_fk
      foreign key (auth_user_id) references auth.users(id) on delete cascade;
  end if;
end $$;
create unique index if not exists profiles_auth_user_id_uidx on public.profiles(auth_user_id);

