  GN.lang = GN.ls.get(
    (window.GN_CONFIG && window.GN_CONFIG.STORAGE && window.GN_CONFIG.STORAGE.LANG) || 'gn_lang',
    null
  ) || (window.GN_CONFIG && window.GN_CONFIG.DEFAULT_LANG) || 'ar';

  GN.t = function(key, fallback){
    var dict = GN.i18n[GN.lang] || GN.i18n.ar;
    var val = dict[key];
    if (val != null) return val;
    var fb = GN.i18n.ar[key];
    if (fb != null) return fb;
    return fallback || key;
  };

  GN.setLang = function(lang){
    if (lang !== 'ar' && lang !== 'en') lang = 'ar';
    GN.lang = lang;
    GN.ls.set(
      (window.GN_CONFIG && window.GN_CONFIG.STORAGE && window.GN_CONFIG.STORAGE.LANG) || 'gn_lang',
      lang
    );
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
    GN.applyTranslations();
  };

  GN.applyTranslations = function(root){
    var scope = root || document;
    var dict = GN.i18n[GN.lang] || GN.i18n.ar;

    var els = scope.querySelectorAll('[data-i18n]');
    for (var i = 0; i < els.length; i++) {
      var k = els[i].getAttribute('data-i18n');
      if (dict[k] != null) els[i].textContent = dict[k];
    }

    var htmls = scope.querySelectorAll('[data-i18n-html]');
    for (var j = 0; j < htmls.length; j++) {
      var k2 = htmls[j].getAttribute('data-i18n-html');
      if (dict[k2] != null) htmls[j].innerHTML = dict[k2];
    }

    var phs = scope.querySelectorAll('[data-i18n-placeholder]');
    for (var p = 0; p < phs.length; p++) {
      var k3 = phs[p].getAttribute('data-i18n-placeholder');
      if (dict[k3] != null) phs[p].setAttribute('placeholder', dict[k3]);
    }

    var tls = scope.querySelectorAll('[data-i18n-title]');
    for (var t = 0; t < tls.length; t++) {
      var k4 = tls[t].getAttribute('data-i18n-title');
      if (dict[k4] != null) tls[t].setAttribute('title', dict[k4]);
    }

    var label = GN.lang === 'ar' ? 'EN' : 'ع';
    var lbl1 = document.getElementById('langLabel');
    var lbl2 = document.getElementById('langLabelDash');
    if (lbl1) lbl1.textContent = label;
    if (lbl2) lbl2.textContent = label;
  };

  GN.toggleLang = function(){
    GN.setLang(GN.lang === 'ar' ? 'en' : 'ar');
  };

